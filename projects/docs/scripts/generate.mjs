// Generates the docs site's data from source, so nothing on the site can drift from the code.
//   src/app/generated/examples.ts       every example component, and its source text for the Code tab
//   src/app/generated/api.json          inputs, outputs and methods of every public library class
//   src/app/generated/component-docs.ts slug, title and description of every component page
// Run with `npm run docs:gen`. `npm start` and the docs build run it first.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const app = path.join(root, 'projects/docs/src/app');
const out = path.join(app, 'generated');
const lib = path.join(root, 'projects/hr-ui/src');

const walk = dir =>
  fs.existsSync(dir)
    ? fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => {
        const p = path.join(dir, e.name);
        return e.isDirectory() ? walk(p) : [p];
      })
    : [];
const write = (file, text) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text);
};
const rel = (from, to) => {
  const r = path.relative(path.dirname(from), to).replace(/\\/g, '/').replace(/\.ts$/, '');
  return r.startsWith('.') ? r : './' + r;
};

// 1. Examples: one standalone component per file, default export, under src/app/examples/<group>/<name>.ts
const exampleFiles = walk(path.join(app, 'examples')).filter(f => f.endsWith('.ts') && !f.endsWith('.spec.ts')).sort();
const names = new Map();
for (const f of exampleFiles) {
  const name = path.basename(f, '.ts');
  if (names.has(name)) throw new Error(`Two examples are named "${name}": ${names.get(name)} and ${f}`);
  if (!/export default class/.test(fs.readFileSync(f, 'utf8'))) throw new Error(`${f} must default-export its component class`);
  names.set(name, f);
}
const examplesFile = path.join(out, 'examples.ts');
fs.rmSync(path.join(out, 'example-sources'), { recursive: true, force: true });
for (const [name, f] of names) {
  const source = fs.readFileSync(f, 'utf8').trimEnd() + '\n';
  write(path.join(out, 'example-sources', `${name}.ts`), `export default ${JSON.stringify(source)};\n`);
}
write(
  examplesFile,
  `// Generated by projects/docs/scripts/generate.mjs. Do not edit.
import type { Type } from '@angular/core';

export interface ExampleEntry {
  load: () => Promise<Type<unknown>>;
  source: () => Promise<string>;
}

export const EXAMPLES: Record<string, ExampleEntry> = {
${[...names]
  .map(
    ([name, f]) =>
      `  '${name}': {\n    load: () => import('${rel(examplesFile, f)}').then(m => m.default),\n    source: () => import('./example-sources/${name}').then(m => m.default)\n  }`
  )
  .join(',\n')}
};
`
);

// 2. Component pages: src/app/content/components/<slug>.ts, each exporting `doc`.
const contentFiles = walk(path.join(app, 'content/components')).filter(f => f.endsWith('.ts')).sort();
const docsFile = path.join(out, 'component-docs.ts');
const field = (src, key) => {
  const m = src.match(new RegExp(`\\b${key}:\\s*(['"\`])((?:\\\\.|(?!\\1).)*)\\1`, 's'));
  return m ? m[2] : null;
};
const pages = contentFiles.map(f => {
  const src = fs.readFileSync(f, 'utf8');
  const slug = field(src, 'slug');
  const title = field(src, 'title');
  const description = field(src, 'description');
  if (!slug || !title || !description) throw new Error(`${f} needs slug, title and description string fields`);
  if (slug !== path.basename(f, '.ts')) throw new Error(`${f}: slug "${slug}" must match the file name`);
  for (const m of src.matchAll(/name:\s*'([^']+)'/g)) {
    if (!names.has(m[1])) throw new Error(`${f} uses example "${m[1]}", which has no file under src/app/examples`);
  }
  return { slug, title, description, file: f };
});
write(
  docsFile,
  `// Generated by projects/docs/scripts/generate.mjs. Do not edit.
import type { ComponentDoc } from '../docs/types';

export interface ComponentDocEntry {
  slug: string;
  title: string;
  description: string;
  load: () => Promise<ComponentDoc>;
}

export const COMPONENT_DOCS: ComponentDocEntry[] = [
${pages
  .map(
    p =>
      `  {\n    slug: ${JSON.stringify(p.slug)},\n    title: ${JSON.stringify(p.title)},\n    description: ${JSON.stringify(p.description)},\n    load: () => import('${rel(docsFile, p.file)}').then(m => m.doc)\n  }`
  )
  .join(',\n')}
];
`
);

// 3. API reference from the library source, through the TypeScript type checker.
const configPath = path.join(root, 'projects/hr-ui/tsconfig.lib.json');
const parsed = ts.getParsedCommandLineOfConfigFile(configPath, {}, { ...ts.sys, onUnRecoverableConfigFileDiagnostic: d => console.error(d) });
const program = ts.createProgram(parsed.fileNames, parsed.options);
const checker = program.getTypeChecker();
const flags = ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseSingleQuotesForStringLiteralType;

const docOf = node => {
  const symbol = node.name && checker.getSymbolAtLocation(node.name);
  return symbol ? ts.displayPartsToString(symbol.getDocumentationComment(checker)).trim() : '';
};
const typeText = type => {
  // A named union of literals reads best in the order its author wrote it.
  const aliasDecl = type.aliasSymbol?.declarations?.[0];
  if (aliasDecl && ts.isTypeAliasDeclaration(aliasDecl) && ts.isUnionTypeNode(aliasDecl.type) && aliasDecl.type.types.every(t => ts.isLiteralTypeNode(t))) {
    return aliasDecl.type.types.map(t => t.getText().replace(/"/g, "'")).join(' | ');
  }
  // A huge union (every icon name) is unreadable in a table: show its alias, or string.
  if (type.isUnion() && type.types.length > 12) {
    if (type.aliasSymbol) return type.aliasSymbol.name;
    const others = type.types
      .filter(t => !(t.flags & ts.TypeFlags.StringLiteral))
      .map(t => checker.typeToString(t, undefined, flags))
      .filter(s => s !== 'string & {}' && s !== 'string');
    return ['string', ...new Set(others)].join(' | ');
  }
  if (type.isUnion() && type.types.length <= 12) {
    const parts = type.types.map(t => checker.typeToString(t, undefined, flags));
    // booleans arrive as `false | true`; show them as one word
    const set = new Set(parts);
    if (set.has('false') && set.has('true')) {
      set.delete('false');
      set.delete('true');
      return ['boolean', ...set].join(' | ');
    }
    return parts.join(' | ');
  }
  return checker.typeToString(type, undefined, flags);
};
const signalArg = (type, index = 0) => {
  const args = checker.getTypeArguments(type) ?? type.aliasTypeArguments ?? [];
  return args[index];
};
const decoratorCall = (node, name) =>
  ts.getDecorators(node)?.find(d => ts.isCallExpression(d.expression) && d.expression.expression.getText() === name)?.expression;
const objectProp = (obj, key) =>
  obj && ts.isObjectLiteralExpression(obj)
    ? obj.properties.find(p => ts.isPropertyAssignment(p) && p.name.getText() === key)?.initializer
    : undefined;

const api = {};
for (const sf of program.getSourceFiles()) {
  if (!sf.fileName.startsWith(lib) || sf.fileName.endsWith('.spec.ts')) continue;
  ts.forEachChild(sf, node => {
    if (!ts.isClassDeclaration(node) || !node.name) return;
    if (!node.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword)) return;
    const component = decoratorCall(node, 'Component');
    const directive = decoratorCall(node, 'Directive');
    const pipe = decoratorCall(node, 'Pipe');
    const service = decoratorCall(node, 'Service') ?? decoratorCall(node, 'Injectable');
    const meta = component ?? directive ?? pipe;
    if (!meta && !service) return;
    const metaObj = meta?.arguments[0];
    const selector = objectProp(metaObj, 'selector');
    const pipeName = objectProp(metaObj, 'name');
    const entry = {
      name: node.name.text,
      kind: component ? 'component' : directive ? 'directive' : pipe ? 'pipe' : 'service',
      selector: selector && ts.isStringLiteralLike(selector) ? selector.text : pipeName && ts.isStringLiteralLike(pipeName) ? pipeName.text : null,
      description: docOf(node),
      file: path.relative(root, sf.fileName),
      inputs: [],
      outputs: [],
      methods: []
    };
    for (const member of node.members) {
      const isPrivate = member.modifiers?.some(m => m.kind === ts.SyntaxKind.PrivateKeyword || m.kind === ts.SyntaxKind.ProtectedKeyword);
      if (isPrivate || !member.name || ts.isPrivateIdentifier(member.name)) continue;
      const memberName = member.name.getText();
      if (ts.isPropertyDeclaration(member) && member.initializer && ts.isCallExpression(member.initializer)) {
        const call = member.initializer;
        const callee = call.expression.getText();
        const options = ['input', 'model'].includes(callee) ? call.arguments[1] : callee.endsWith('.required') ? call.arguments[0] : callee === 'output' ? call.arguments[0] : undefined;
        const alias = objectProp(options, 'alias');
        const publicName = alias && ts.isStringLiteralLike(alias) ? alias.text : memberName;
        const type = checker.getTypeAtLocation(member);
        if (callee === 'input' || callee === 'input.required' || callee === 'model' || callee === 'model.required') {
          const hasTransform = !!objectProp(options, 'transform');
          // InputSignalWithTransform<Read, Write>: callers pass the write type
          const valueType = hasTransform ? signalArg(type, 1) ?? signalArg(type, 0) : signalArg(type, 0);
          entry.inputs.push({
            name: publicName,
            type: valueType ? typeText(valueType) : 'unknown',
            default: callee.endsWith('.required') ? null : call.arguments[0] ? call.arguments[0].getText() : 'undefined',
            required: callee.endsWith('.required'),
            twoWay: callee.startsWith('model'),
            description: docOf(member)
          });
        } else if (callee === 'output' || callee === 'outputFromObservable') {
          const valueType = signalArg(type, 0);
          entry.outputs.push({ name: publicName, type: valueType ? typeText(valueType) : 'void', description: docOf(member) });
        }
      } else if (ts.isPropertyDeclaration(member) && decoratorCall(member, 'Input')) {
        entry.inputs.push({ name: memberName, type: typeText(checker.getTypeAtLocation(member)), default: member.initializer?.getText() ?? 'undefined', required: false, twoWay: false, description: docOf(member) });
      } else if (ts.isPropertyDeclaration(member) && decoratorCall(member, 'Output')) {
        entry.outputs.push({ name: memberName, type: typeText(signalArg(checker.getTypeAtLocation(member)) ?? checker.getTypeAtLocation(member)), description: docOf(member) });
      } else if (entry.kind === 'service' && ts.isMethodDeclaration(member)) {
        const sig = checker.getSignatureFromDeclaration(member);
        if (!sig) continue;
        const params = sig.getParameters().map(p => {
          const decl = p.valueDeclaration;
          const optional = decl && ts.isParameter(decl) && (decl.questionToken || decl.initializer) ? '?' : '';
          return `${p.name}${optional}: ${checker.typeToString(checker.getTypeOfSymbolAtLocation(p, member), undefined, flags)}`;
        });
        entry.methods.push({ name: memberName, signature: `${memberName}(${params.join(', ')}): ${checker.typeToString(sig.getReturnType(), undefined, flags)}`, description: docOf(member) });
      }
    }
    api[entry.name] = entry;
  });
}
write(path.join(out, 'api.json'), JSON.stringify(api, null, 2) + '\n');

console.log(`docs:gen  ${names.size} examples, ${pages.length} component pages, ${Object.keys(api).length} API entries`);
